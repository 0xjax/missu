/**
 * 色源 → 静态色板。
 *
 * NOTE: 壁纸取色没有静态色板（由系统按壁纸生成，见 `resolveColorScheme`）；这一支
 * 只是兜底，取品牌色板。低版本没有系统色板，设置页也不会给出那块色块。
 */
internal fun ColorSource.staticColorScheme(darkTheme: Boolean): ColorScheme = when (this) {
    ColorSource.WALLPAPER -> if (darkTheme) BrandDark else BrandLight
    ColorSource.BRAND -> if (darkTheme) BrandDark else BrandLight
    ColorSource.VIOLET -> if (darkTheme) VioletDark else VioletLight
    ColorSource.BLUE -> if (darkTheme) BlueDark else BlueLight
    ColorSource.TEAL -> if (darkTheme) TealDark else TealLight
    ColorSource.AMBER -> if (darkTheme) AmberDark else AmberLight
}

